#!/usr/bin/env node
/**
 * Merge the three SOPS gates' machine-readable results into the single
 * `results.json` and `traceability.md` the evidence directory carries.
 *
 *   node scripts/sops-evidence.mjs
 *
 * It only merges. It never invents a result: a case no gate recorded is
 * reported as `not-run`, and the exit code is non-zero so a missing gate
 * cannot be mistaken for a pass.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "docs/evidence/2026-09-22-browser-local-sops");

const SOURCES = [
  ["browser-results.json", "pnpm verify:sops-browser"],
  ["conformance-results.json", "pnpm verify:sops-conformance"],
  ["cloud-live.json", "pnpm verify:sops-cloud-live"],
];

const TOTAL = 80;
const id = (n) => `SB-${String(n).padStart(3, "0")}`;

const byCase = new Map();
const missingSources = [];
for (const [file, command] of SOURCES) {
  const path = join(dir, file);
  if (!existsSync(path)) {
    missingSources.push(`${file} (run \`${command}\`)`);
    continue;
  }
  for (const record of JSON.parse(readFileSync(path, "utf8"))) {
    const existing = byCase.get(record.caseId) ?? [];
    byCase.set(record.caseId, [...existing, { source: file, ...record }]);
  }
}

const cases = [];
for (let n = 1; n <= TOTAL; n += 1) {
  const caseId = id(n);
  const records = byCase.get(caseId);
  if (!records) {
    cases.push({
      caseId,
      status: "not-run",
      reason: "No gate recorded a result for this case.",
      records: [],
    });
    continue;
  }
  // Worst status wins: a case proven one way and blocked another is not
  // simply "passed".
  const rank = { failed: 0, "not-run": 1, "blocked-external": 2, passed: 3 };
  const worst = records.reduce((low, record) =>
    (rank[record.status] ?? 1) < (rank[low.status] ?? 1) ? record : low,
  );
  cases.push({
    caseId,
    status: worst.status,
    reason: worst.reason,
    records,
  });
}

const tally = {};
for (const item of cases) tally[item.status] = (tally[item.status] ?? 0) + 1;

writeFileSync(
  join(dir, "results.json"),
  `${JSON.stringify(
    {
      $comment:
        "Merged from the three gates' own outputs by scripts/sops-evidence.mjs. Do not hand-edit: re-run the gates.",
      generatedAt: new Date().toISOString(),
      sources: SOURCES.map(([file, command]) => ({ file, command })),
      missingSources,
      tally,
      cases,
    },
    null,
    2,
  )}\n`,
);

const row = (item) => {
  const record = item.records[0];
  return `| ${item.caseId} | ${item.status} | ${record?.evidenceKind ?? "—"} | ${record?.command ?? "—"} | ${(item.reason ?? "").replace(/\|/gu, "\\|")} |`;
};

writeFileSync(
  join(dir, "traceability.md"),
  `# Traceability — acceptance matrix SB-001 … SB-${String(TOTAL).padStart(3, "0")}

Generated by \`node scripts/sops-evidence.mjs\` from the three gates' own
machine-readable output. Every row's status comes from a gate that ran; a
case no gate recorded reads **not-run**, never "passed".

**Status here is a claim about what executed, not a claim of security.** A
\`passed\` row means the named gate asserted that behaviour on this commit.
It does not mean the case was audited, that it holds on every browser, or
that a provider not exercised here works.

| status | count |
| --- | --- |
${Object.entries(tally)
  .sort()
  .map(([status, count]) => `| ${status} | ${count} |`)
  .join("\n")}

${missingSources.length ? `> **Incomplete:** ${missingSources.join(", ")}.\n` : ""}
## Cases

| case | status | evidence | gate | note |
| --- | --- | --- | --- | --- |
${cases.map(row).join("\n")}

## Statuses

- **passed** — a gate executed the obligation and asserted it.
- **blocked-external** — the obligation needs a resource outside this
  repository (a disposable cloud KMS key) that was not supplied. Reported
  separately and never counted as a pass.
- **failed** — a gate executed the obligation and it did not hold.
- **not-run** — no gate recorded this case. Treat as unproven.
`,
);

console.log(
  `results.json + traceability.md — ${Object.entries(tally)
    .map(([status, count]) => `${count} ${status}`)
    .join(", ")}`,
);
const unproven = (tally["not-run"] ?? 0) + (tally.failed ?? 0);
if (missingSources.length)
  console.error(`incomplete: missing ${missingSources.join(", ")}`);
process.exit(unproven > 0 || missingSources.length > 0 ? 1 : 0);
