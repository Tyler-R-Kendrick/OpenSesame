/**
 * Rendering for the authority-fabric report (work item TEST-REPORT).
 *
 * Kept apart from the gate so the entry point is collection, execution and
 * verdicts only. Nothing here decides a status; it only presents them.
 */

export function markdown(report) {
  const rows = report.scenarios.map(
    (entry) =>
      `| \`${entry.id}\` | ${entry.workItem} | ${entry.tier} | ${entry.invariant} | **${entry.status}** | ${entry.title} | ${entry.reason ?? ""} |`,
  );
  const tiers = report.tierVocabulary.map((tier) => {
    const counts = report.summary.byTier[tier];
    const parts = Object.entries(counts)
      .filter(([, count]) => count > 0)
      .map(([status, count]) => `${count} ${status}`);
    return `| ${tier} | ${parts.length === 0 ? "—" : parts.join(", ")} |`;
  });
  return `# Authority fabric — verification report

Generated by \`pnpm test:authority-fabric\` at ${report.generatedAt}.
HEAD \`${report.head ?? "unknown"}\`${report.treeDirty ? ", working tree dirty" : ""}.
${
  report.treeChangedDuringRun
    ? "\n> The working tree changed while this ran, so scenarios were resolved\n> against different states and cannot be compared with one another. Re-run\n> against a still tree before reading any single row as settled.\n"
    : ""
}

**Gate: ${report.summary.gate.toUpperCase()}** — ${report.summary.total} scenarios: ${Object.entries(
    report.summary.byStatus,
  )
    .map(([status, count]) => `${count} ${status}`)
    .join(", ")}.

A scenario passes only when a named test in a wired module ran and passed.
\`blocked\` means the harness could not settle the contract and fails the gate;
\`unsupported\` is a declared limit recorded with what would lift it.

## By tier

| Tier | Scenarios |
|---|---|
${tiers.join("\n")}

## Scenarios

| ID | Work item | Tier | Contract | Status | Scenario | Reason |
|---|---|---|---|---|---|---|
${rows.join("\n")}
`;
}

export function printSummary(current) {
  const counts = Object.entries(current.summary.byStatus)
    .map(([status, count]) => `${count} ${status}`)
    .join(", ");
  process.stdout.write(
    `authority fabric: ${current.summary.total} scenarios — ${counts}\n`,
  );
  for (const entry of current.scenarios) {
    if (entry.status === "pass") continue;
    process.stdout.write(
      `  ${entry.status.padEnd(11)} ${entry.id} ${entry.invariant}  ${entry.reason ?? ""}\n`,
    );
  }
  process.stdout.write(
    "report: docs/evidence/general-authority/authority-fabric-report.json\n",
  );
}
