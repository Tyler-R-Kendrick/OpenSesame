#!/usr/bin/env node
import { spawnSync } from "node:child_process";
/**
 * Export deepsec queue + report snapshot into docs/security/deepsec/ (tracked).
 */
import fs from "node:fs";
import path from "node:path";

const repoRoot = process.argv[2] ?? process.cwd();
const outDir = path.join(repoRoot, "docs/security/deepsec");
const agent = process.env.DEEPSEC_AGENT ?? "kimi";
const model =
  process.env.DEEPSEC_GROK_MODEL ??
  (agent === "kimi" ? "kimi-code/k3" : "grok-4.7");

function runNode(script, args = []) {
  const proc = spawnSync("node", [script, ...args], {
    cwd: repoRoot,
    encoding: "utf8",
    env: process.env,
  });
  if (proc.status !== 0) {
    throw new Error(proc.stderr || proc.stdout || `${script} failed`);
  }
  return proc.stdout;
}

const reportJson = runNode(
  path.join(repoRoot, "scripts/audit/deepsec-grok-report-data.mjs"),
  [repoRoot],
);
const report = JSON.parse(reportJson);
const queueJson = runNode(
  path.join(repoRoot, "scripts/audit/deepsec-grok-fix-queue.mjs"),
  [repoRoot],
);
const queue = JSON.parse(queueJson);

fs.mkdirSync(outDir, { recursive: true });
const stamp = new Date().toISOString();
const meta = {
  exportedAt: stamp,
  agent,
  model,
  triageTotals: report.triageTotals,
  stats: report.stats,
  queueLength: queue.total,
  falsePositiveCount: queue.falsePositives?.length ?? 0,
};

fs.writeFileSync(
  path.join(outDir, "meta.json"),
  `${JSON.stringify(meta, null, 2)}\n`,
);
fs.writeFileSync(path.join(outDir, "report-rows.json"), reportJson);
fs.writeFileSync(path.join(outDir, "fix-queue.json"), queueJson);

const bySeverity = {};
const byVerdict = {};
for (const row of report.rows) {
  bySeverity[row.severity] = (bySeverity[row.severity] ?? 0) + 1;
  byVerdict[row.verdict] = (byVerdict[row.verdict] ?? 0) + 1;
}

const readme = `# deepsec fix queue export

Auto-generated by \`scripts/audit/deepsec-export-docs.mjs\`. Do not hand-edit JSON;
re-run export after rescan/triage.

| Field | Value |
| --- | --- |
| Exported (UTC) | ${stamp} |
| Agent | \`${agent}\` |
| Model | \`${model}\` |
| Queue | ${queue.total} findings |
| False positives | ${queue.falsePositives?.length ?? 0} |

## Scan coverage (process status)

| Area | Analyzed | Pending | Error | Candidates |
| --- | ---: | ---: | ---: | ---: |
| core | ${report.stats.core.analyzed} | ${report.stats.core.pending} | ${report.stats.core.error} | ${report.stats.core.candidates} |
| pwa | ${report.stats.pwa.analyzed} | ${report.stats.pwa.pending} | ${report.stats.pwa.error} | ${report.stats.pwa.candidates} |
| cli | ${report.stats.cli.analyzed} | ${report.stats.cli.pending} | ${report.stats.cli.error} | ${report.stats.cli.candidates} |

${
  report.stats.core.error +
    report.stats.pwa.error +
    report.stats.cli.error >
  0
    ? "> **Incomplete:** errors mean Kimi investigation did not finish for those files (often the 5-hour subscription quota). Re-run `scripts/audit/deepsec-kimi-resume.sh` before treating triage totals as complete.\n"
    : ""
}

## Triage totals

| P0 | P1 | P2 | skip |
| ---: | ---: | ---: | ---: |
| ${report.triageTotals.P0} | ${report.triageTotals.P1} | ${report.triageTotals.P2} | ${report.triageTotals.skip} |

## Severity (all rows)

| Severity | Count |
| --- | ---: |
${Object.entries(bySeverity)
  .sort((a, b) => a[0].localeCompare(b[0]))
  .map(([k, v]) => `| ${k} | ${v} |`)
  .join("\n")}

## Verdict

| Verdict | Count |
| --- | ---: |
${Object.entries(byVerdict)
  .map(([k, v]) => `| ${k} | ${v} |`)
  .join("\n")}

## Files

- \`fix-queue.json\` — ordered remediation queue (\`scripts/audit/deepsec-grok-fix-queue.mjs\`)
- \`report-rows.json\` — flat finding rows + per-area stats
- \`meta.json\` — export metadata
`;

fs.writeFileSync(path.join(outDir, "README.md"), readme);
process.stdout.write(
  `deepsec-export-docs: wrote ${outDir} (${queue.total} queued)\n`,
);
