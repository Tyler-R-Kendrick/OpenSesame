#!/usr/bin/env node
/**
 * Emit `src/ceremony-routes.generated.ts` from
 * `spec/config/ceremony-routes.json` (ADR 0139, ADR 0140 §3).
 * `src/ceremony-routes.test.ts` fails when the two disagree.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const specPath = join(here, "../../../spec/config/ceremony-routes.json");
const outputPath = join(here, "../src/ceremony-routes.generated.ts");

export function renderModule(raw = readFileSync(specPath, "utf8")) {
  const { routes, legacy } = JSON.parse(raw);
  return [
    "// Generated by scripts/emit-ceremony-routes.mjs from",
    "// spec/config/ceremony-routes.json — do not edit.",
    `export const CEREMONY_ROUTES_JSON =\n  ${JSON.stringify(JSON.stringify({ routes, legacy }))};`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(outputPath, renderModule());
  console.log(`wrote ${outputPath}`);
}
