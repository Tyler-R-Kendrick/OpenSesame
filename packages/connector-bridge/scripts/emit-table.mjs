/**
 * The hosts the connector bridge may reach, per provider, derived from the
 * specs that already say which providers a page cannot reach by itself
 * (ADR 0139: one definition, a freshness test in the consumer):
 *
 *   - `spec/connectors/browser-policy.json` — an API-key method refused on the
 *     strength of a probe from the audited origin.
 *   - `spec/connectors/oauth-reach.json` — a registered OAuth application's
 *     token, resource or revocation endpoint a page could not read (ADR 0218),
 *     and the `*.suffix` families a person's own tenant may live at.
 *
 * Only a provider with a key check to carry is in the table: a row in
 * `browser-dispositions.json` that refuses browsers and has no connect preset
 * has nothing for the bridge to send.
 *
 * A provider's hosts are what its own evidence names (the probe), what the
 * catalog declares as its egress and the host of its key check. Hosts that are
 * templates (`{site}`) are tenant-specific and are not guessed. MCP rules are
 * left out: an MCP server streams, and the bridge returns one buffered body.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../../..");
const spec = (name) =>
  JSON.parse(readFileSync(join(root, "spec/connectors", name), "utf8"));

const LITERAL_HOST = /^[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?$/;
const TENANT_FAMILY = /^\*\.[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?$/;
const hostOf = (url) => {
  try {
    return new URL(url).hostname;
  } catch {
    return null;
  }
};

/** `name: [...]` as the repository's formatter lays it out: one line if it fits in 80 columns, else one host per line. */
function listLines(name, list) {
  const inline = `    ${name}: [${list.map((host) => JSON.stringify(host)).join(", ")}],`;
  if (inline.length <= 80) return [inline];
  return [
    `    ${name}: [`,
    ...list.map((host) => `      ${JSON.stringify(host)},`),
    "    ],",
  ];
}

const emptyRow = () => ({
  authorities: new Set(),
  oauth: new Set(),
  tenants: new Set(),
});

/** Provider id → the literal hosts its own evidence, catalog row and key check name. */
function collectHosts() {
  const rows = new Map();
  const row = (id) => {
    if (!rows.has(id)) rows.set(id, emptyRow());
    return rows.get(id);
  };
  const add = (id, host) => {
    if (host && LITERAL_HOST.test(host)) row(id).authorities.add(host);
  };
  for (const rule of spec("browser-policy.json").rules)
    if (rule.method === "api-key")
      add(rule.provider_id, hostOf(rule.probe?.url ?? ""));
  addDeclared(rows, add);
  addOAuth(row);
  return rows;
}

/** A registered OAuth application's endpoints a page cannot read, and its tenant families. */
function addOAuth(row) {
  for (const provider of spec("oauth-reach.json").providers) {
    for (const endpoint of provider.endpoints) {
      // The token exchange and the account check are what a connection calls;
      // revocation is recorded as evidence but is not called (ADR 0218).
      if (endpoint.stage === "revocation") continue;
      const host =
        endpoint.direct || endpoint.tenant ? null : hostOf(endpoint.url);
      if (host && LITERAL_HOST.test(host))
        row(provider.provider_id).oauth.add(host);
    }
    for (const pattern of provider.tenant_hosts ?? []) {
      if (!TENANT_FAMILY.test(pattern))
        throw new Error(`Not a tenant family: ${pattern}`);
      row(provider.provider_id).tenants.add(pattern);
    }
  }
}

/** What the catalog and the key check declare for the providers already named. */
function addDeclared(rows, add) {
  const catalog = new Map(
    spec("catalog.view.json").providers.map((row) => [row.id, row]),
  );
  const presets = new Map(
    spec("connect-presets.json").api_key.map((row) => [row.service, row]),
  );
  for (const id of [...rows.keys()]) {
    for (const authority of catalog.get(id)?.egress?.authorities ?? [])
      add(id, authority);
    const verify = presets.get(id)?.verify?.url;
    if (verify) add(id, hostOf(verify));
  }
}

export function renderTable() {
  const rows = [...collectHosts().entries()]
    .filter(
      ([, sets]) =>
        sets.authorities.size + sets.oauth.size + sets.tenants.size > 0,
    )
    .sort(([a], [b]) => a.localeCompare(b))
    .flatMap(([id, sets]) => [
      "  {",
      `    providerId: ${JSON.stringify(id)},`,
      ...listLines("authorities", [...sets.authorities].sort()),
      ...(sets.oauth.size ? listLines("oauth", [...sets.oauth].sort()) : []),
      ...(sets.tenants.size
        ? listLines("tenants", [...sets.tenants].sort())
        : []),
      "  },",
    ]);
  return [
    "// Generated by scripts/emit-table.mjs from spec/connectors/{browser-policy,browser-dispositions,catalog.view,connect-presets,oauth-reach}.json — do not edit.",
    "/** Each provider a browser cannot reach by itself, and the exact hosts the bridge may send its requests to. */",
    "export const BRIDGE_TABLE = [",
    ...rows,
    "] as const;",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(here, "../src/table.generated.ts"), renderTable());
  console.log("wrote src/table.generated.ts");
}
