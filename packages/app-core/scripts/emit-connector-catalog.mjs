#!/usr/bin/env node
/**
 * Emit `src/lib/connector-catalog.generated.ts` from
 * `spec/connectors/catalog.view.json`.
 *
 * The view is the Host API's own projection of `spec/connectors/catalog.json`
 * (`GET /api/v1/providers`), written by the connection-broker test
 * `catalog_view`. This module embeds it for the client plane, so a provider's
 * name, category, auth kind, scopes, egress and fields are the same on every
 * target and nothing here re-derives them. `connector-catalog.test.ts` fails
 * when this output has drifted from the view.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const viewPath = join(here, "../../../spec/connectors/catalog.view.json");
const outputPath = join(here, "../src/lib/connector-catalog.generated.ts");

export function renderModule(raw = readFileSync(viewPath, "utf8")) {
  const view = JSON.parse(raw);
  const aliases = {};
  const rows = view.providers.map(({ aliases: names = [], ...row }) => {
    for (const name of names) aliases[name] = row.id;
    return `  ${JSON.stringify(JSON.stringify(row))},`;
  });
  return [
    "// Generated by scripts/emit-connector-catalog.mjs from",
    "// spec/connectors/catalog.view.json — do not edit.",
    `export const CATALOG_REVISION = ${JSON.stringify(view.revision)};`,
    "",
    "/** Other names a row goes by, mapped to its id. */",
    "export const CATALOG_ALIASES: Readonly<Record<string, string>> = {",
    ...Object.entries(aliases).map(
      ([alias, id]) => `  ${JSON.stringify(alias)}: ${JSON.stringify(id)},`,
    ),
    "};",
    "",
    "/** One Host API provider view per row, as JSON (`ProviderSchema`). */",
    "export const CATALOG_ROW_JSON: readonly string[] = [",
    ...rows,
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(outputPath, renderModule());
  console.log(`wrote ${outputPath}`);
}
