#!/usr/bin/env node
/**
 * Emit `src/lib/connector-catalog.generated.ts` from
 * `spec/connectors/catalog.view.json`.
 *
 * The view is the Host API's own projection of `spec/connectors/catalog.json`
 * (`GET /api/v1/providers`), written by the connection-broker test
 * `catalog_view`. This module embeds it for the client plane, so a provider's
 * name, category, auth kind, scopes, egress and fields are the same on every
 * target and nothing here re-derives them. `connector-catalog.test.ts` fails
 * when this output has drifted from the view.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const viewPath = join(here, "../../../spec/connectors/catalog.view.json");
const outputPath = join(here, "../src/lib/connector-catalog.generated.ts");

/** Identical public root fields are stored once, then reconstructed for each complete provider view. */
export function factorCatalogRows(rows) {
  const first = rows[0] ?? {};
  const common = Object.fromEntries(
    Object.keys(first)
      .filter((key) =>
        rows.every(
          (row) => JSON.stringify(row[key]) === JSON.stringify(first[key]),
        ),
      )
      .map((key) => [key, first[key]]),
  );
  const sparse = rows.map((row) =>
    Object.fromEntries(
      Object.entries(row).filter(([key]) => !Object.hasOwn(common, key)),
    ),
  );
  return { common, rows: sparse };
}

export function renderModule(raw = readFileSync(viewPath, "utf8")) {
  const view = JSON.parse(raw);
  const aliases = {};
  const rows = view.providers.map(({ aliases: names = [], ...row }) => {
    for (const name of names) aliases[name] = row.id;
    return row;
  });
  const factored = factorCatalogRows(rows);
  return [
    "// Generated by scripts/emit-connector-catalog.mjs from",
    "// spec/connectors/catalog.view.json — do not edit.",
    `export const CATALOG_REVISION = ${JSON.stringify(view.revision)};`,
    "",
    "/** Other names a row goes by, mapped to its id. */",
    "export const CATALOG_ALIASES = {",
    ...Object.entries(aliases).map(
      ([alias, id]) => `  ${JSON.stringify(alias)}: ${JSON.stringify(id)},`,
    ),
    "} as const;",
    "",
    "/** One Host API provider view per row, as JSON (`ProviderSchema`). */",
    `const common = ${JSON.stringify(factored.common)};`,
    "const rows: readonly string[] = [",
    ...factored.rows.map((row) => `  ${JSON.stringify(JSON.stringify(row))},`),
    "];",
    "export const CATALOG_ROW_JSON: readonly string[] = rows.map((row) => JSON.stringify({ ...common, ...JSON.parse(row) }));",
    "",
  ].join("\n");
}

const idsPath = join(here, "../src/lib/ai-model-provider-ids.generated.ts");

/**
 * The ids of the `ai_model_provider` rows, in catalog order, as a module of
 * their own. Bundling decides which rows Pages draws before a Host answers
 * (`bundled-provider-ids.ts`), and that list sits on the boot path, so it
 * cannot import the whole catalog to find them (ADR 0192).
 */
export function renderAiProviderIds(raw = readFileSync(viewPath, "utf8")) {
  const ids = JSON.parse(raw)
    .providers.filter((row) => row.category === "ai_model_provider")
    .map((row) => row.id);
  return [
    "// Generated by scripts/emit-connector-catalog.mjs from",
    "// spec/connectors/catalog.view.json — do not edit.",
    "/** Every `ai_model_provider` row of the catalog, in catalog order. */",
    "export const AI_MODEL_PROVIDER_IDS = [",
    ...ids.map((id) => `  ${JSON.stringify(id)},`),
    "] as const;",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(outputPath, renderModule());
  writeFileSync(idsPath, renderAiProviderIds());
  console.log(`wrote ${outputPath}`);
  console.log(`wrote ${idsPath}`);
}
