#!/usr/bin/env node
/** Compile the account-only guard from the shared Google Drive OAuth preset. */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { isJsonObject, isString } from "../../../scripts/lib/json-boundary.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const sourcePath = join(here, "../../../spec/connectors/connect-presets.json");
const outputPath = join(
  here,
  "../src/lib/native-google-account-policy.generated.ts",
);
const string = (value) => isString(value) && value.length > 0;
const record = isJsonObject;
function httpsEndpoint(value) {
  if (!string(value) || /[{}\\]/.test(value)) return false;
  try {
    const parsed = new URL(value);
    return (
      parsed.protocol === "https:" &&
      !parsed.username &&
      !parsed.password &&
      !parsed.hash
    );
  } catch {
    return false;
  }
}

function accountScopes(row) {
  const allScopes = row.scopes.map((scope) =>
    record(scope) ? scope.name : null,
  );
  if (
    allScopes.some((scope) => !string(scope)) ||
    new Set(allScopes).size !== allScopes.length
  )
    throw new Error("Invalid account scopes");
  const scopes = row.scopes
    .filter((scope) => scope.account_only === true)
    .map((scope) => scope.name);
  if (
    !scopes.length ||
    scopes.some((scope) => !string(scope)) ||
    new Set(scopes).size !== scopes.length
  )
    throw new Error("Invalid account scopes");
  return scopes;
}

function accountAliases(policy, scopes) {
  const aliases = Object.entries(policy.scope_aliases);
  if (
    aliases.some(
      ([alias, target]) =>
        !string(alias) ||
        ["__proto__", "prototype", "constructor"].includes(alias) ||
        !string(target) ||
        !scopes.includes(target) ||
        scopes.includes(alias),
    )
  )
    throw new Error("Invalid account scope alias");
  return Object.fromEntries(aliases);
}

function forbiddenParameters(policy) {
  const forbidden = policy.forbidden_parameters;
  if (
    forbidden.some((key) => !string(key) || !/^[a-z][a-z0-9_]*$/.test(key)) ||
    new Set(forbidden).size !== forbidden.length
  )
    throw new Error("Invalid forbidden account parameter");
  return forbidden;
}

export function googleAccountPolicy(
  presets = JSON.parse(readFileSync(sourcePath, "utf8")),
) {
  if (!record(presets) || !Array.isArray(presets.oauth))
    throw new Error("Invalid account policy");
  const rows = presets.oauth.filter(
    (row) => record(row) && row.service === "google-drive",
  );
  if (rows.length !== 1) throw new Error("Invalid account policy");
  const row = rows[0];
  const policy = row.account_only_policy;
  if (
    !record(policy) ||
    !record(policy.scope_aliases) ||
    !Array.isArray(policy.forbidden_parameters) ||
    !Array.isArray(row.scopes)
  )
    throw new Error("Invalid account policy");
  const endpoints = {
    issuer: row.server_url,
    authorization_endpoint: row.authorization_endpoint,
    token_endpoint: row.token_endpoint,
    resource: row.userinfo_endpoint,
  };
  if (
    !Object.values(endpoints).every(httpsEndpoint) ||
    !record(row.verify) ||
    row.verify.url !== row.userinfo_endpoint
  )
    throw new Error("Invalid account endpoint");
  const scopes = accountScopes(row);
  const aliases = accountAliases(policy, scopes);
  const forbidden = forbiddenParameters(policy);
  return {
    endpoints,
    scopes,
    aliases,
    forbiddenParameters: forbidden,
  };
}

export function renderGoogleAccountPolicy(presets) {
  const policy = googleAccountPolicy(presets);
  return [
    "// Generated by scripts/emit-google-account-policy.mjs from",
    "// spec/connectors/connect-presets.json — do not edit.",
    "export const GOOGLE_ACCOUNT_POLICY = Object.freeze({",
    `  endpoints: Object.freeze(${JSON.stringify(policy.endpoints)}),`,
    `  scopes: Object.freeze(${JSON.stringify(policy.scopes)}),`,
    `  aliases: Object.freeze(${JSON.stringify(policy.aliases)}),`,
    `  forbiddenParameters: Object.freeze(${JSON.stringify(policy.forbiddenParameters)}),`,
    "});",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(outputPath, renderGoogleAccountPolicy());
  console.log(`wrote ${outputPath}`);
}
