#!/usr/bin/env node
/**
 * Emit `src/lib/quorum/item-types.generated.ts` from the two item type
 * definitions the Trusted contacts capability brings:
 * `marketplace/item-types/optional/trusted-circle.json` and
 * `guardian-share.json`.
 *
 * The capability declares no egress, so it cannot fetch its types from the
 * item-type marketplace. It embeds them instead, and `ensureQuorumTypes`
 * installs the embedded text into the open vault. The JSON files stay the one
 * source (the Rust conformance suite and the marketplace pin read the same
 * bytes); `item-types.generated.test.ts` fails when this output has drifted.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const typesDir = join(here, "../../../marketplace/item-types/optional");
const outputPath = join(here, "../src/lib/quorum/item-types.generated.ts");

/** Install order: a circle first, then what a guardian holds of one. */
export const QUORUM_TYPE_IDS = ["trusted-circle", "guardian-share"];

function readType(id) {
  const text = readFileSync(join(typesDir, `${id}.json`), "utf8");
  const { metadata } = JSON.parse(text);
  if (metadata.id !== id) {
    throw new Error(`${id}.json declares the id ${metadata.id}`);
  }
  return { id, version: metadata.version, text };
}

export function renderModule(types = QUORUM_TYPE_IDS.map(readType)) {
  const rows = types.flatMap(({ id, version, text }) => [
    "  {",
    `    id: ${JSON.stringify(id)},`,
    `    version: ${JSON.stringify(version)},`,
    `    text: ${JSON.stringify(text)},`,
    "  },",
  ]);
  return [
    "// Generated by scripts/emit-quorum-types.mjs from",
    "// marketplace/item-types/optional/{trusted-circle,guardian-share}.json",
    "// — do not edit.",
    "",
    "/** The definitions as authored, byte for byte, for `ensureQuorumTypes`. */",
    "export const QUORUM_TYPES = [",
    ...rows,
    "] as const;",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(outputPath, renderModule());
  console.log(`wrote ${outputPath}`);
}
