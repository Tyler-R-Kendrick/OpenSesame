#!/usr/bin/env node
/**
 * Emit `src/lib/password-reset/mail-type.generated.ts` from the one item type
 * the Password reset capability keeps its mailboxes in:
 * `marketplace/item-types/optional/email-account.json`.
 *
 * The capability declares no egress for fetching item types, so it cannot take
 * the type from the item-type marketplace. It embeds the text instead, and
 * `ensureResetMailType` installs it into the open vault. The JSON file stays
 * the one source (the Rust conformance suite and the marketplace pin read the
 * same bytes); `mail-type.generated.test.ts` fails when this output has drifted.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const typesDir = join(here, "../../../marketplace/item-types/optional");
const outputPath = join(
  here,
  "../src/lib/password-reset/mail-type.generated.ts",
);

export const RESET_MAIL_TYPE_IDS = ["email-account"];

function readType(id) {
  const text = readFileSync(join(typesDir, `${id}.json`), "utf8");
  const { metadata } = JSON.parse(text);
  if (metadata.id !== id) {
    throw new Error(`${id}.json declares the id ${metadata.id}`);
  }
  return { id, version: metadata.version, text };
}

export function renderModule(types = RESET_MAIL_TYPE_IDS.map(readType)) {
  const rows = types.flatMap(({ id, version, text }) => [
    "  {",
    `    id: ${JSON.stringify(id)},`,
    `    version: ${JSON.stringify(version)},`,
    `    text: ${JSON.stringify(text)},`,
    "  },",
  ]);
  return [
    "// Generated by scripts/emit-reset-mail-types.mjs from",
    "// marketplace/item-types/optional/email-account.json — do not edit.",
    "",
    "/** The definition as authored, byte for byte, for `ensureResetMailType`. */",
    "export const RESET_MAIL_TYPES = [",
    ...rows,
    "] as const;",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(outputPath, renderModule());
  console.log(`wrote ${outputPath}`);
}
