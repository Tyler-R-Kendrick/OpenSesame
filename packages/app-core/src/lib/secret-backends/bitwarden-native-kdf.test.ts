import { createHash, createHmac, hkdfSync, pbkdf2Sync } from "node:crypto";
import { argon2idAsync } from "@noble/hashes/argon2.js";
import { afterEach, expect, it, vi } from "vitest";
import {
  type BitwardenKdf,
  type BitwardenKdfResourceLimits,
  bitwardenLegacyEmailSalt,
  deriveBitwardenMasterKey,
  stretchBitwardenMasterKey,
} from "./bitwarden-native-kdf.js";

const limits: BitwardenKdfResourceLimits = {
  maxPbkdf2Iterations: 6000,
  maxArgon2Iterations: 2,
  maxArgon2MemoryMiB: 16,
  maxArgon2Parallelism: 2,
};
const pbkdf: BitwardenKdf = { kdfType: 0, iterations: 5000 };
const argon: BitwardenKdf = {
  kdfType: 1,
  iterations: 2,
  memoryMiB: 16,
  parallelism: 1,
};
const password = "  Päss\u0065\u0301🔐  ";
const salt = new TextEncoder().encode(" Mixed.Case+salt@Example.test ");
const hex = (bytes: Uint8Array) => Buffer.from(bytes).toString("hex");
const derive = (kdf: BitwardenKdf = pbkdf) =>
  deriveBitwardenMasterKey(password, salt, kdf, limits);

afterEach(() => vi.restoreAllMocks());

it("matches an independently generated PBKDF2-SHA256 known answer", async () => {
  // Synthetic inputs; frozen output generated with Node/OpenSSL PBKDF2.
  const key = await deriveBitwardenMasterKey(
    "password",
    new TextEncoder().encode("salt"),
    pbkdf,
    limits,
  );
  expect(hex(key)).toBe(
    "8fc2bcffbb4b1ac9b9de03588d390f3d9bf336c2c4422c90c158cc714225f629",
  );
});

it("matches Node with untrimmed Unicode password and exact supplied salt", async () => {
  const before = salt.slice();
  const key = await derive();
  expect(hex(key)).toBe(hex(pbkdf2Sync(password, salt, 5000, 32, "sha256")));
  for (const altered of [password.trim(), password.normalize("NFKC")])
    expect(hex(key)).not.toBe(
      hex(pbkdf2Sync(altered, salt, 5000, 32, "sha256")),
    );
  const normalizedSalt = bitwardenLegacyEmailSalt(
    new TextDecoder().decode(salt),
  );
  expect(hex(key)).not.toBe(
    hex(pbkdf2Sync(password, normalizedSalt, 5000, 32, "sha256")),
  );
  expect(salt).toEqual(before);
});

it.each([
  [1, "1072b2ab89197fe4d3f045d8de896beca52daccc98b5d86be47bd6aa05975988"],
  [2, "cc6502d85b2952dca321885eb912df152f555ea13f7d66953465d354770f81c1"],
])(
  "matches independent Argon2id v19 with %i lanes",
  async (parallelism, known) => {
    // Frozen vectors generated by noble; production uses hash-wasm, not noble.
    const digest = createHash("sha256").update(salt).digest();
    const expected = await argon2idAsync(Buffer.from(password), digest, {
      m: 16 * 1024,
      t: 2,
      p: parallelism,
      version: 19,
      dkLen: 32,
      maxmem: 32 * 1024 * 1024,
    });
    const actual = await derive({ ...argon, parallelism });
    expect(hex(expected)).toBe(known);
    expect(hex(actual)).toBe(known);
    expect(hex(actual)).not.toBe(
      hex(pbkdf2Sync(password, salt, 5000, 32, "sha256")),
    );
  },
);

it("does not substitute raw salt for the required SHA256 salt digest", async () => {
  const wrong = await argon2idAsync(Buffer.from(password), salt, {
    m: 16384,
    t: 2,
    p: 1,
    version: 19,
    dkLen: 32,
    maxmem: 32 * 1024 * 1024,
  });
  expect(hex(wrong)).not.toBe(
    "1072b2ab89197fe4d3f045d8de896beca52daccc98b5d86be47bd6aa05975988",
  );
});

it("normalizes only the separately named legacy email salt", () => {
  expect(
    new TextDecoder().decode(bitwardenLegacyEmailSalt("  A@EXAMPLE.TEST  ")),
  ).toBe("a@example.test");
});

it("stretches with Expand-only enc/mac halves, not Extract+Expand", () => {
  const master = Uint8Array.from({ length: 32 }, (_, i) => i);
  const before = master.slice();
  const expanded = stretchBitwardenMasterKey(master);
  const expected = Buffer.concat(
    ["enc", "mac"].map((info) =>
      createHmac("sha256", master)
        .update(info)
        .update(Buffer.from([1]))
        .digest(),
    ),
  );
  expect(hex(expanded)).toBe(hex(expected));
  expect(hex(expanded)).toBe(
    "9c5639fac602366b486253191cb7900d7d8e3a1514676b118d5803a11dd97213c" +
      "ce388b4ac0f05edee78d40dcbe78a7715640de75ed9ba06942fb42398d6b1f1",
  );
  expect(expanded.slice(0, 32)).not.toEqual(
    new Uint8Array(hkdfSync("sha256", master, Buffer.alloc(0), "enc", 32)),
  );
  expect(master).toEqual(before);
  expanded.fill(0);
  expect(master).toEqual(before);
});

it.each([0, 31, 33, 64])("rejects master key length %i", (length) => {
  expect(() => stretchBitwardenMasterKey(new Uint8Array(length))).toThrow(
    "Invalid Bitwarden master key.",
  );
});

const invalidNumbers = [
  Number.NaN,
  Number.POSITIVE_INFINITY,
  Number.NEGATIVE_INFINITY,
  0,
  -1,
  1.5,
  2 ** 53,
];
const invalidKdfs = [
  null,
  {},
  { kdfType: 2, iterations: 5000 },
  { kdfType: "0", iterations: 5000 },
  ...[...invalidNumbers, 4999, 6001].map((iterations) => ({
    ...pbkdf,
    iterations,
  })),
  ...[...invalidNumbers, 1, 3].map((iterations) => ({ ...argon, iterations })),
  ...[...invalidNumbers, 15, 17, Number.MAX_SAFE_INTEGER].map((memoryMiB) => ({
    ...argon,
    memoryMiB,
  })),
  ...[...invalidNumbers, 3].map((parallelism) => ({ ...argon, parallelism })),
];

it.each(invalidKdfs)(
  "rejects invalid or over-policy KDF %j before work",
  async (kdf) => {
    const subtle = vi.spyOn(crypto.subtle, "importKey");
    // SAFETY: deliberately malformed wire input exercises runtime rejection.
    await expect(derive(kdf as BitwardenKdf)).rejects.toThrow(
      /Invalid Bitwarden key derivation parameters|Unsupported Bitwarden key derivation algorithm/,
    );
    expect(subtle).not.toHaveBeenCalled();
  },
);

const policyFields = [
  ["maxPbkdf2Iterations", 4999, 2_000_001],
  ["maxArgon2Iterations", 1, 11],
  ["maxArgon2MemoryMiB", 15, 1025],
  ["maxArgon2Parallelism", 0, 17],
] as const;

it.each(policyFields)(
  "bounds explicit resource policy %s",
  async (field, below, above) => {
    const subtle = vi.spyOn(crypto.subtle, "importKey");
    for (const value of [...invalidNumbers, below, above]) {
      await expect(
        deriveBitwardenMasterKey(password, salt, pbkdf, {
          ...limits,
          [field]: value,
        }),
      ).rejects.toThrow("Invalid Bitwarden key derivation parameters.");
    }
    expect(subtle).not.toHaveBeenCalled();
  },
);

it("requires an explicit policy and accepts policy ceilings without allocating them", async () => {
  await expect(
    // SAFETY: missing required policy is deliberately exercised at runtime.
    deriveBitwardenMasterKey(password, salt, pbkdf, undefined as never),
  ).rejects.toThrow("resource policy is required");
  const key = await deriveBitwardenMasterKey(password, salt, pbkdf, {
    maxPbkdf2Iterations: 2_000_000,
    maxArgon2Iterations: 10,
    maxArgon2MemoryMiB: 1024,
    maxArgon2Parallelism: 16,
  });
  expect(hex(key)).toBe(hex(pbkdf2Sync(password, salt, 5000, 32, "sha256")));
});

it.each(["", "x".repeat(4097), "€".repeat(1366), "\ud800", "\udc00"])(
  "rejects empty, oversized, or malformed password before work",
  async (invalid) => {
    const subtle = vi.spyOn(crypto.subtle, "importKey");
    await expect(
      deriveBitwardenMasterKey(invalid, salt, pbkdf, limits),
    ).rejects.toThrow("Invalid Bitwarden key derivation input.");
    expect(subtle).not.toHaveBeenCalled();
  },
);

it.each([new Uint8Array(), new Uint8Array(4097), null])(
  "rejects empty, oversized, or non-byte salt before work",
  async (invalid) => {
    const subtle = vi.spyOn(crypto.subtle, "importKey");
    await expect(
      // SAFETY: null deliberately exercises the byte contract boundary.
      deriveBitwardenMasterKey(password, invalid as Uint8Array, pbkdf, limits),
    ).rejects.toThrow("Invalid Bitwarden key derivation input.");
    expect(subtle).not.toHaveBeenCalled();
  },
);

it("accepts exact byte ceilings without trimming", async () => {
  const largePassword = "🔐".repeat(1024);
  const largeSalt = new Uint8Array(4096).fill(7);
  expect(
    hex(
      await deriveBitwardenMasterKey(largePassword, largeSalt, pbkdf, limits),
    ),
  ).toBe(hex(pbkdf2Sync(largePassword, largeSalt, 5000, 32, "sha256")));
  expect(() => bitwardenLegacyEmailSalt(" ".repeat(4097))).toThrow(/input/);
  expect(() => bitwardenLegacyEmailSalt("   ")).toThrow(/input/);
});

it("snapshots caller salt and parameters before asynchronous work", async () => {
  const ownSalt = salt.slice();
  const config = { ...pbkdf };
  const expected = pbkdf2Sync(password, ownSalt, 5000, 32, "sha256");
  const pending = deriveBitwardenMasterKey(password, ownSalt, config, limits);
  ownSalt.fill(0);
  config.iterations = 6000;
  expect(hex(await pending)).toBe(hex(expected));
});

it("wipes owned PBKDF2 inputs on real success without wiping caller salt", async () => {
  const imported = vi.spyOn(crypto.subtle, "importKey");
  const derived = vi.spyOn(crypto.subtle, "deriveBits");
  const before = salt.slice();
  await derive();
  expect(imported.mock.calls[0][1]).toEqual(
    new Uint8Array(Buffer.byteLength(password)),
  );
  // SAFETY: the observed real primitive call matches the PBKDF2 contract.
  const params = derived.mock.calls[0][0] as Pbkdf2Params;
  expect(params.salt).toEqual(new Uint8Array(salt.length));
  expect(salt).toEqual(before);
});

it("wipes owned inputs and sanitizes primitive errors", async () => {
  const imported = vi.spyOn(crypto.subtle, "importKey");
  let ownedSalt: BufferSource | undefined;
  vi.spyOn(crypto.subtle, "deriveBits").mockImplementation(
    async (parameters) => {
      // SAFETY: this test scope observes the PBKDF2-only primitive call.
      ownedSalt = (parameters as Pbkdf2Params).salt;
      throw new Error(`primitive included ${password}`);
    },
  );
  const before = salt.slice();
  await expect(derive()).rejects.toThrow(/^Bitwarden key derivation failed\.$/);
  expect(imported.mock.calls[0][1]).toEqual(
    new Uint8Array(Buffer.byteLength(password)),
  );
  expect(ownedSalt).toEqual(new Uint8Array(salt.length));
  expect(salt).toEqual(before);
});
