#!/usr/bin/env node
/**
 * Emit `src/endpoints.generated.ts` from `spec/config/endpoints.json`
 * (ADR 0139). `src/endpoints.test.ts` fails when the two disagree.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const specPath = join(here, "../../../spec/config/endpoints.json");
const outputPath = join(here, "../src/endpoints.generated.ts");

export function renderModule(raw = readFileSync(specPath, "utf8")) {
  const { endpoints } = JSON.parse(raw);
  return [
    "// Generated by scripts/emit-endpoints.mjs from",
    "// spec/config/endpoints.json — do not edit.",
    `export const ENDPOINTS_JSON =\n  ${JSON.stringify(JSON.stringify(endpoints))};`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(outputPath, renderModule());
  console.log(`wrote ${outputPath}`);
}
