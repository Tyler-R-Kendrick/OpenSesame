#!/usr/bin/env node
/**
 * Emit `src/definitions.generated.ts` from `definitions/*.json`.
 *
 * The JSON files are the single corpus: this package embeds them for the
 * client plane and `crates/vault-item-types` embeds the same files with
 * `include_str!` for the host plane (ADR 0078 §8). Generating a module rather
 * than importing JSON keeps the package loadable under both Node's ESM
 * resolver and Vite without an import attribute in either.
 *
 * `src/definitions.generated.test.ts` fails if this output has drifted, so
 * editing a definition without re-running this script cannot merge.
 */

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const definitionsDir = join(here, "..", "definitions");
const outputPath = join(here, "..", "src", "definitions.generated.ts");

export function renderModule() {
  const names = readdirSync(definitionsDir)
    .filter((name) => name.endsWith(".json"))
    .sort();
  const entries = names.map((name) => {
    const text = readFileSync(join(definitionsDir, name), "utf8").trimEnd();
    return `  ${JSON.stringify(name.replace(/\.json$/, ""))}: ${JSON.stringify(text)},`;
  });
  return [
    "// Generated by scripts/emit-definitions.mjs — do not edit.",
    "// Source of truth: packages/vault-item-types/definitions/*.json",
    "",
    "/** Every built-in definition, keyed by type id, as authored JSON text. */",
    "export const BUILTIN_DEFINITION_JSON = {",
    ...entries,
    "} satisfies Readonly<Record<string, string>>;",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(outputPath, renderModule(), "utf8");
  process.stdout.write(`wrote ${outputPath}\n`);
}
