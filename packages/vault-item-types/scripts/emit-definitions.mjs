#!/usr/bin/env node
/**
 * Emit the client plane's view of `marketplace/item-types/builtin/*.json`.
 *
 * The JSON files are the single corpus: this package embeds the core ones for
 * the client plane and `crates/vault-item-types` embeds all of them with
 * `include_str!` for the host plane (ADR 0087). Generating modules rather than
 * importing JSON keeps the package loadable under both Node's ESM resolver and
 * Vite without an import attribute in either.
 *
 * The corpus is split in two (ADR 0164):
 *
 *   - `src/definitions.generated.ts` — the CORE types, embedded. These are the
 *     kinds a minimal vault creates or a capability owns, so they are in the
 *     entry bundle.
 *   - `src/packs.generated.ts` — a metadata index of every other type plus a
 *     loader per type, and `src/packs/<id>.generated.ts`, one module per type
 *     holding its definition text. Each is reached only through a dynamic
 *     `import()`, so the bundler emits it as its own chunk and nothing fetches
 *     it until a person switches the type on.
 *
 * `src/registry.test.ts` fails if any output has drifted, so editing a
 * definition without re-running this script cannot merge.
 */

import { createHash } from "node:crypto";
import {
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const definitionsDir = join(
  here,
  "..",
  "..",
  "..",
  "marketplace",
  "item-types",
  "builtin",
);
const srcDir = join(here, "..", "src");

/**
 * The types the entry bundle keeps: the base secret and the file that
 * projects onto it, and the three a capability of its own owns (ADR 0153).
 * Every other built-in is a pack.
 */
export const CORE_IDS = ["certificate", "drop", "file", "passkey", "secret"];

const HEADER = [
  "// Generated by scripts/emit-definitions.mjs — do not edit.",
  "// Source of truth: marketplace/item-types/builtin/*.json",
];

function corpus() {
  return readdirSync(definitionsDir)
    .filter((name) => name.endsWith(".json"))
    .sort()
    .map((name) => {
      const id = name.replace(/\.json$/, "");
      const text = readFileSync(join(definitionsDir, name), "utf8").trimEnd();
      return { id, text, json: JSON.parse(text) };
    });
}

function fieldCount(json) {
  return (json.spec.sections ?? []).reduce(
    (total, section) => total + (section.fields ?? []).length,
    0,
  );
}

function indexEntry({ id, text, json }) {
  const { spec, metadata } = json;
  return {
    id,
    title: spec.title,
    plural: spec.plural,
    extension: spec.extension,
    summary: spec.summary,
    categories: spec.categories ?? [],
    version: metadata.version,
    fields: fieldCount(json),
    bytes: Buffer.byteLength(text, "utf8"),
    sha256: createHash("sha256").update(text, "utf8").digest("hex"),
  };
}

export function renderCore() {
  const entries = corpus()
    .filter(({ id }) => CORE_IDS.includes(id))
    .map(({ id, text }) => `  ${JSON.stringify(id)}: ${JSON.stringify(text)},`);
  return [
    ...HEADER,
    "",
    "/** The embedded built-in definitions, keyed by type id, as authored JSON text. */",
    "export const BUILTIN_DEFINITION_JSON = {",
    ...entries,
    "} satisfies Readonly<Record<string, string>>;",
    "",
  ].join("\n");
}

export function renderPackModule({ text }) {
  return [
    ...HEADER,
    "",
    `const text: string = ${JSON.stringify(text)};`,
    "export default text;",
    "",
  ].join("\n");
}

export function renderPackIndex() {
  const packs = corpus().filter(({ id }) => !CORE_IDS.includes(id));
  return [
    ...HEADER,
    "",
    "/** What the app knows of a pack without having fetched it. */",
    "export type PackEntry = {",
    "  readonly id: string;",
    "  readonly title: string;",
    "  readonly plural: string;",
    "  readonly extension: string;",
    "  readonly summary: string;",
    "  readonly categories: readonly string[];",
    "  readonly version: string;",
    "  readonly fields: number;",
    "  /** UTF-8 length of the definition text: the size of the download. */",
    "  readonly bytes: number;",
    "  /** Hex SHA-256 of the definition text, checked before it is parsed. */",
    "  readonly sha256: string;",
    "};",
    "",
    "export const PACK_INDEX: readonly PackEntry[] = [",
    ...packs.map((pack) => `  ${JSON.stringify(indexEntry(pack))},`),
    "];",
    "",
    "/** One dynamic import per pack, so each is its own chunk. */",
    "export const PACK_LOADERS = new Map([",
    ...packs.map(
      ({ id }) =>
        `  [${JSON.stringify(id)}, () => import("./packs/${id}.generated.js")],`,
    ),
    "]);",
    "",
  ].join("\n");
}

/** Every generated file as `[absolute path, contents]`. */
export function renderAll() {
  const packs = corpus().filter(({ id }) => !CORE_IDS.includes(id));
  return [
    [join(srcDir, "definitions.generated.ts"), renderCore()],
    [join(srcDir, "packs.generated.ts"), renderPackIndex()],
    ...packs.map((pack) => [
      join(srcDir, "packs", `${pack.id}.generated.ts`),
      renderPackModule(pack),
    ]),
  ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  rmSync(join(srcDir, "packs"), { recursive: true, force: true });
  mkdirSync(join(srcDir, "packs"), { recursive: true });
  for (const [path, contents] of renderAll()) {
    writeFileSync(path, contents, "utf8");
  }
  process.stdout.write(`wrote ${renderAll().length} files under ${srcDir}\n`);
}
